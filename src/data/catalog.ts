import type { Deity, Festival, Occasion, Prayer, PrayerKind } from "./types";

type Draft = {
  id: string;
  title: string;
  deities: Deity[];
  occasions?: Occasion[];
  festivals?: Festival[];
  kind?: PrayerKind;
  sanskrit: string;
  transliteration: string;
  meaning: string;
  tags?: string[];
};

function p(d: Draft): Prayer {
  return {
    id: d.id,
    title: d.title,
    deities: d.deities,
    occasions: d.occasions?.length ? d.occasions : ["anytime"],
    festivals: d.festivals ?? [],
    kind: d.kind ?? "mantra",
    sanskrit: d.sanskrit,
    transliteration: d.transliteration,
    meaning: d.meaning,
    tags: d.tags ?? [],
  };
}

